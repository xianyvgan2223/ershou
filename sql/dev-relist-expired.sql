-- =============================================================
-- 第 4 轮 · 开发期数据修复：把「已过期」商品全部重新上架
-- =============================================================
-- 对应契约：智能体团队/第4轮-移动端严选与开发期限时-设计.md 第 1.2 节
-- 背景：用户反馈"开发期间取消商品限时，把之前过期的商品全部上架，要不然商品太少了"。
--       当前库里 17 件商品有 13 件 status=7（已过期），在售只剩 3 件，不便测试/演示。
--
-- 内容：
--   1) 已过期(7) 的个人商品：全部恢复在售(2)，清空到期时间，并刷新发布时间（重新曝光到列表前面）
--   2) 平台商品（seller_type=2，在售 2 / 已售出 4）：只清空到期时间，不改状态
--      （已售出的要留成交记录，不能复活；平台商品由 seller_type=2 识别，与个人商品分开处理）
--
-- 幂等：可重复执行，第二遍影响 0 行
--   - 条件都是 status=7 / seller_type=2，执行后这些行已不满足条件
--   - 只动 status=7，不碰 4 已售出 / 5 已下架 / 3 锁定 / 8 违规下架
--
-- 前置条件（重要）：后端需以 ITEM_VALIDITY_ENABLED=false（或库里随时会再次过期时给超大
-- ITEM_VALID_DAYS）启动，并已执行 sql/migration-platform.sql（item.seller_type 列存在），
-- 否则这 13 件商品会在下一个小时的到期任务里被重新置回 7。
--
-- 用法（由 Lead 统一执行，item-member 不写库）：
--   mysql --host=127.0.0.1 --port=3306 --user=ershou --password=*** --database=ershou --default-character-set=utf8mb4 < sql/dev-relist-expired.sql
--
-- 执行后验证（期望 status=2 共 16 件、status=7 共 0 件）：
--   SELECT status, COUNT(*) FROM item GROUP BY status ORDER BY status;
-- =============================================================

SET NAMES utf8mb4;

-- -------------------------------------------------------------
-- 1. 已过期(7) → 在售(2)：清空到期时间 + 刷新发布时间
--    （发布时间按最新排，避免这批商品在列表里一直沉底；updated_at 同步以便 ES 增量同步收敛）
-- -------------------------------------------------------------
UPDATE item
   SET status       = 2,
       expire_at    = NULL,
       published_at = NOW(),
       updated_at   = NOW()
 WHERE status = 7;

-- -------------------------------------------------------------
-- 2. 平台商品（seller_type=2）：清空到期时间，状态保持不变
--    只清在售(2)/已售出(4) —— 已售出要留成交记录，不能因为清到期时间而改状态
-- -------------------------------------------------------------
UPDATE item
   SET expire_at  = NULL,
       updated_at = NOW()
 WHERE seller_type = 2
   AND status IN (2, 4);

-- -------------------------------------------------------------
-- 3. 执行后核对（人工看结果；期望 status=2 共 16、status=7 共 0）
-- -------------------------------------------------------------
SELECT status, COUNT(*) AS cnt
  FROM item
 GROUP BY status
 ORDER BY status;
